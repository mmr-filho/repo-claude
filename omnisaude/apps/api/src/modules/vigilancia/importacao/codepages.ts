import type { CodigoPagina } from '@omnisaude/shared';

/**
 * Códigos de página do DBF do Sinan (VIG-1c, frente F2). O byte 29 do cabeçalho (language driver) diz a codificação;
 * 0x00 (sem marca) é decidido pela pontuação das letras portuguesas decodificadas em CP850 e em CP1252 (empate: CP850).
 */
export const CODIGO_PAGINA_DO_BYTE: Readonly<Record<number, CodigoPagina>> = {
  0x01: 'CP437',
  0x02: 'CP850',
  0x25: 'CP850',
  0x24: 'CP860',
  0x03: 'CP1252',
  0x57: 'CP1252',
  0x58: 'CP1252',
  0x59: 'CP1252',
};

/** Codificação pelo byte 29; null quando o byte não marca nenhuma (0x00 ou desconhecido). */
export function codigoPaginaDoCabecalho(byte29: number): CodigoPagina | null {
  return CODIGO_PAGINA_DO_BYTE[byte29] ?? null;
}

