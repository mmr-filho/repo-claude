const ALTOS: Readonly<Record<CodigoPagina, string>> = Object.fromEntries(Object.entries(PONTOS).map(([cp, pontos]) => [cp, String.fromCharCode(...pontos)])) as Record<CodigoPagina, string>;

/** Texto do campo na codificação (os bytes abaixo de 0x80 são ASCII nas quatro). */
export function decodificar(bytes: Uint8Array, codificacao: CodigoPagina): string {
  const altos = ALTOS[codificacao];
  let s = '';
  for (let i = 0; i < bytes.length; i++) {
    const b = bytes[i]!;
    s += b < 0x80 ? String.fromCharCode(b) : altos[b - 0x80]!;
  }
  return s;
}

/** Letras do português que podem aparecer num nome, num bairro ou num município. */
const LETRAS_PT = new Set('ÁÉÍÓÚÂÊÔÃÕÀÇÜáéíóúâêôãõàçü');
/** Ordinais e grau: comuns em endereço ("Nº", "1º"), neutros na pontuação. */
const NEUTROS = new Set('ºª°');
const LETRA_ASCII = /[A-Za-z]/;
const maiuscula = (c: string) => c !== c.toLowerCase();

/**
 * Pontos de um texto decodificado: cada letra portuguesa vale 2, mais 1 se a caixa bate com a letra vizinha (e menos 1
 * se não bate: "SÃO" em CP850 lido como CP1252 vira "SÇO", mas "SÓ" vira "Sà"); qualquer outro caractere acima de
 * 0x7F (caixa de desenho, símbolo, controle) tira 2.
 */
function pontuar(texto: string): number {
  let pontos = 0;
  for (let i = 0; i < texto.length; i++) {
    const c = texto[i]!;
    if (c.charCodeAt(0) < 0x80 || NEUTROS.has(c)) continue;
    if (!LETRAS_PT.has(c)) {
      pontos -= 2;
      continue;
    }
    pontos += 2;
    const vizinha = [texto[i - 1], texto[i + 1]].find((v) => v !== undefined && LETRA_ASCII.test(v));
    if (vizinha) pontos += maiuscula(vizinha) === maiuscula(c) ? 1 : -1;
  }
  return pontos;
}

/** Codificação mais provável de um DBF sem marca: pontua as letras portuguesas em CP850 e em CP1252 (empate: CP850). */
export function escolherCodificacao(amostras: Uint8Array[]): CodigoPagina {
  let cp850 = 0;
  let cp1252 = 0;
  for (const a of amostras) {
    if (!a.some((b) => b >= 0x80)) continue;
    cp850 += pontuar(decodificar(a, 'CP850'));
    cp1252 += pontuar(decodificar(a, 'CP1252'));
  }
  return cp1252 > cp850 ? 'CP1252' : 'CP850';
}

/** Bytes de um texto em CP1252 (leitura do CSV que não é UTF-8 válido). */
export function decodificarCp1252(bytes: Uint8Array): string {
  // Em pedaços, para não montar uma string caractere a caractere num arquivo grande.
  const partes: string[] = [];
  const passo = 1 << 16;
  for (let i = 0; i < bytes.length; i += passo) partes.push(decodificar(bytes.subarray(i, i + passo), 'CP1252'));
  return partes.join('');
}
